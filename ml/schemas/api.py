"""API request and response schemas adhering to RFC 7807 problem details."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from ml.schemas.enums import ScanWorkflowState
from ml.schemas.extraction import RawMedicineExtraction
from ml.schemas.matcher import MANDATORY_DISCLAIMER
from ml.schemas.quality import ImageQualityReport


class ScanResponse(BaseModel):
    """Response payload for POST /v1/scan."""
    scan_id: str = Field(..., description="Unique anonymous scan identifier.")
    status: ScanWorkflowState = Field(..., description="Current perception workflow state.")
    extraction: Optional[RawMedicineExtraction] = Field(
        default=None,
        description="Structured extraction result; null if image rejected or perception failed."
    )
    quality_report: Optional[ImageQualityReport] = Field(
        default=None,
        description="Pre-extraction image quality check report."
    )
    field_status: Dict[str, str] = Field(
        default_factory=dict,
        description="Confidence classification per field: 'high', 'medium', 'low', 'unreadable'."
    )
    candidate_products: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Resolved candidate products for user review."
    )
    warnings: List[str] = Field(
        default_factory=list,
        description="Non-blocking perception notices or discrepancies."
    )
    next_action: str = Field(
        ...,
        description="Action required from client: 'retake', 'confirm_fields', 'ready_to_match', 'manual_search'."
    )
    model_version: str = Field(default="gemini-2.5-flash-v1")
    latency_ms: int = Field(..., ge=0)
    disclaimer: str = Field(default=MANDATORY_DISCLAIMER)


class ProblemDetails(BaseModel):
    """RFC 7807 compliant problem details object for structured error reporting."""
    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type."
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type."
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server."
    )
    detail: str = Field(
        ...,
        description="A human-readable explanation specific to this occurrence of the problem."
    )
    instance: Optional[str] = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem."
    )
    code: str = Field(
        ...,
        description="Stable machine-readable error code: e.g. 'LOW_CONFIDENCE', 'UNRESOLVED_BRAND', 'VISION_UNAVAILABLE'."
    )
    disclaimer: str = Field(default=MANDATORY_DISCLAIMER)
